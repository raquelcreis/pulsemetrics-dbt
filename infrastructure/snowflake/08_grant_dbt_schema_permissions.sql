TO ROLE PULSEMETRICS_DBT;

GRANT CREATE VIEW ON SCHEMA PULSEMETRICS.STAGING
TO ROLE PULSEMETRICS_DBT;


GRANT USAGE ON SCHEMA PULSEMETRICS.INTERMEDIATE
TO ROLE PULSEMETRICS_DBT;

GRANT CREATE TABLE ON SCHEMA PULSEMETRICS.INTERMEDIATE
TO ROLE PULSEMETRICS_DBT;

GRANT CREATE VIEW ON SCHEMA PULSEMETRICS.INTERMEDIATE
TO ROLE PULSEMETRICS_DBT;


