
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS PULSEMETRICS_INGEST;

GRANT ROLE PULSEMETRICS_INGEST
TO USER PULSEMETRICS_DBT_USER;

GRANT USAGE ON WAREHOUSE PULSEMETRICS_WH
TO ROLE PULSEMETRICS_INGEST;

GRANT USAGE ON DATABASE PULSEMETRICS
TO ROLE PULSEMETRICS_INGEST;

GRANT USAGE ON SCHEMA PULSEMETRICS.RAW
TO ROLE PULSEMETRICS_INGEST;

GRANT SELECT, INSERT, DELETE
ON ALL TABLES IN SCHEMA PULSEMETRICS.RAW
TO ROLE PULSEMETRICS_INGEST;

GRANT CREATE STAGE
ON SCHEMA PULSEMETRICS.RAW
TO ROLE PULSEMETRICS_INGEST;
